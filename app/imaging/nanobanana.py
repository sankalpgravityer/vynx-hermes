# Longest edge of a source photograph handed to the model, and the JPEG quality
# it is re-encoded at.
#
# The originals are 6 MB camera files. The model does not need that, the upload
# is the slowest part of a call, and on a rate-limited pub-*.r2.dev host a 6 MB
# GET is the one that gets cut off mid-body. The TypeScript path never sees this
# because the analyze worker feeds it already-compressed files; this path reads
# straight from R2, so it compresses here instead.
_SOURCE_MAX_PX = 1536
_SOURCE_QUALITY = 88


def compress_source(data: bytes) -> bytes:
    """Downscale to a sane size and flatten to JPEG.

    Flattening matters as much as the resize: a cut-out PNG has a transparent
    background, and every part is declared to the API as image/jpeg. Compositing
    onto white first means the model sees a clean garment on a white field rather
    than however it chooses to interpret an alpha channel it was told is opaque.

    Returns the input untouched if it cannot be decoded — an unreadable buffer is
    the caller's problem to report, not this function's to swallow.
    """
    try:
        from PIL import Image

        img = Image.open(io.BytesIO(data))
        img.load()
        if img.mode in ("RGBA", "LA", "P"):
            flat = Image.new("RGB", img.size, (255, 255, 255))
            img = img.convert("RGBA")
            flat.paste(img, mask=img.split()[-1])
            img = flat
        else:
            img = img.convert("RGB")
        img.thumbnail((_SOURCE_MAX_PX, _SOURCE_MAX_PX), Image.Resampling.LANCZOS)
        buf = io.BytesIO()
        img.save(buf, "JPEG", quality=_SOURCE_QUALITY)
        return buf.getvalue()
    except Exception as exc:  # noqa: BLE001
        log.warning("could not compress a source image (%s); sending as-is",
                    type(exc).__name__)
        return data


def _lower(value: Any) -> str:
    return value.lower().strip() if isinstance(value, str) else ""


def _trait(value: str | None) -> str | None:
    """A personality trait worth putting in the prompt.

    'any' is the UI's "no preference" and must not reach the model as a literal
    — "any skin tone" is an instruction, and a worse one than saying nothing.
    """
    if not value or not value.strip():
        return None
    text = value.strip()
    return None if text.lower() == "any" else text


def _canonical_gender(value: str | None) -> str | None:
    """'male' | 'female' | None, from any of the spellings in use."""
    low = _lower(value)
    if low in ("men", "man", "male"):
        return "male"
    if low in ("women", "woman", "female"):
        return "female"
    return None


def choose_personality(
    settings: ImagerySettings, product_gender: str | None, rng: Any = None
) -> dict[str, Any] | None:
    """Pick one of the tenant's named models for this product.

    Mirrors analyze.worker.ts. A personality carries its own gender, so a men's
    product only draws from male personalities and a women's only from female —
    otherwise the catalog shows a woman modelling a men's shirt. A personality
    with no gender set is legacy and stays eligible for anything, and when the
    product's own gender is unknown no filter applies at all.

    Random by design: the point is a catalog that looks like a shop with several
    models rather than one person wearing everything. Callers that need the SAME
    face again — filling in a missing view beside an existing render — must reuse
    the stored traits instead of calling this.
    """
    if not settings.personalities_enabled:
        return None

    wanted = _canonical_gender(product_gender)
    pool = [
        p for p in settings.personalities
        if isinstance(p, dict) and p.get("enabled") is not False
        and (
            wanted is None
            or _canonical_gender(p.get("gender")) is None
            or _canonical_gender(p.get("gender")) == wanted
        )
    ]
    if not pool:
        return None

    import random

    return (rng or random).choice(pool)


def apply_personality(
    settings: ImagerySettings, personality: dict[str, Any] | None
) -> ImagerySettings:
    """Flatten a personality's traits onto a copy of the settings.

    The personality's `age` OVERRIDES the tenant default — a cast entry says "24"
    where the tenant setting says "young adult", and the specific number is the
    point of having named models. Ethnicity and body type deliberately stay on
    the tenant defaults, matching the TypeScript.

    Accepts BOTH shapes this is called with, which differ in one key: a cast
    entry from `ImageGenerationSettings.personalities` carries `name`, while the
    copy stored on `Product.imageSettings` carries `personalityName`. Reading
    only the first silently dropped the name on the reuse path, so a product's
    saved model came back anonymous and the next gap-fill drew a new one.
    """
    if not personality:
        return settings

    return settings.model_copy(update={
        "age": personality.get("age") or settings.age,
        "skin_tone": personality.get("skinTone"),
        "hair_color": personality.get("hairColor"),
        "hair_style": personality.get("hairStyle"),
        "tattoos": personality.get("tattoos"),
        "piercings": personality.get("piercings"),
        "personality_notes": personality.get("notes")
        or personality.get("personalityNotes"),
        "personality_name": personality.get("name")
        or personality.get("personalityName"),
    })


def is_bottom_garment(category: str | None, sub_category: str | None) -> bool:
    cat, sub = _lower(category), _lower(sub_category)
    return any(k in cat or k in sub for k in BOTTOM_GARMENT_KEYWORDS)


# WORD-BOUNDARY for these two, unlike the top/bottom lists above, which match on
# substrings. A substring "cap" classifies CAPRI TROUSERS as headwear and a
# substring "boot" classifies BOOTCUT JEANS as footwear — both real categories,
# and both would be framed as something the customer is not buying.
_FOOTWEAR_RE = re.compile(
    r"\b(footwear|shoes?|sneakers?|trainers?|boots?|sandals?|heels?|loafers?"
    r"|pumps?|mules?|clogs?|espadrilles?|slippers?)\b",
    re.IGNORECASE,
)

# Worn, but not on the torso or the legs — so neither the top framing nor the
# bottom framing puts the product anywhere near the middle of the frame.
_ACCESSORY_RE = re.compile(
    r"\b(accessor(?:y|ies)|bags?|backpacks?|rucksacks?|handbags?|totes?|purses?"
    r"|satchels?|clutch(?:es)?|caps?|hats?|beanies?|belts?|scar(?:f|ves)"
    r"|gloves?|wallets?|sunglasses|watch(?:es)?|jewell?ery|ties?)\b",
    re.IGNORECASE,
)


def is_footwear_garment(category: str | None, sub_category: str | None) -> bool:
    return any(_FOOTWEAR_RE.search(v or "") for v in (category, sub_category))


def is_accessory_garment(category: str | None, sub_category: str | None) -> bool:
    return any(_ACCESSORY_RE.search(v or "") for v in (category, sub_category))


def accessory_region(category: str | None, sub_category: str | None) -> str:
    """Where on the body an accessory actually sits.

    One class, but the crop has to follow the product: a bag hangs at the
    shoulder, a cap sits on the head, a belt at the waist. Framing all of them
    the same way reproduces the bug this class exists to fix, just at a
    different height.
    """
    text = f"{_lower(category)} {_lower(sub_category)}"
    if re.search(r"\b(caps?|hats?|beanies?|sunglasses)\b", text):
        return "head and shoulders"
    if re.search(r"\b(belts?)\b", text):
        return "waist and hips"
    if re.search(r"\b(scar(?:f|ves)|ties?)\b", text):
        return "neck and shoulders"
    if re.search(r"\b(gloves?|watch(?:es)?)\b", text):
        return "hands and forearms"
    return "shoulder and torso"


def classify_garment_type(category: str | None, sub_category: str | None) -> str | None:
    """'footwear' | 'accessory' | 'bottom' | 'top' | None.

    The product CATEGORY, never `mannequinType` — the mobile and decision flows
    set mannequinType to a model type ("Men Top", "Women Top", "Kids") regardless
    of the garment, so a pair of jeans arrives as "Men Top" and would be framed
    and styled as a shirt.

    Footwear and accessories are tested FIRST because they are the narrowest and
    the most specific: their regexes require whole words, so anything they match
    really is that thing, whereas the top/bottom lists match substrings and would
    happily claim "Backpacks & Bags" for nothing at all.
    """
    if is_footwear_garment(category, sub_category):
        return "footwear"
    if is_accessory_garment(category, sub_category):
        return "accessory"
    if is_bottom_garment(category, sub_category):
        return "bottom"
    cat, sub = _lower(category), _lower(sub_category)
    if any(k in cat or k in sub for k in TOP_GARMENT_KEYWORDS):
        return "top"
    return None


def background_image_prompt(value: str | None) -> str:
    if not value:
        return ""
    if value in _BACKGROUND_PROMPTS:
        return _BACKGROUND_PROMPTS[value]
    if value.startswith("#"):
        return f"solid {value} color background"
    return _SIMPLE_COLORS.get(value.lower(), value)


def resolve_aspect_ratio(value: str | None, supported: list[str]) -> str | None:
    """None means "apply no constraint" — 'auto', empty, or unsupported.

    '5:7' is offered in the UI to mirror the image editor but has no native Gemini
    equivalent, so it maps to the closest supported portrait ratio.
    """
    if not value or value == "auto":
        return None
    if value == "5:7":
        return "3:4"
    return value if value in supported else None


def resolve_image_size(value: str | None, default: str = "2K") -> str:
    upper = (value or "").upper()
    return upper if upper in ("1K", "2K", "4K") else default


