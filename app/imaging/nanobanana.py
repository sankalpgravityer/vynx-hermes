"""Cloth-on-model generation with Nano Banana Pro.

A PORT of vnyx-api's `services/banana-nano.ts`, and deliberately a faithful one.
Both paths write into the same gallery, so a product backfilled from here sits
next to products generated by the analyze worker. If the prompts drift, the two
sets of renders stop looking like the same shop — different framing, a different
kind of model, a different backdrop — and that is visible to a customer in a way
no test would catch. `tests/test_nanobanana_prompt.py` pins the text for exactly
that reason.

The same reasoning fixes the model id in policy rather than leaving it to an env
var: `gemini-3-pro-image-preview` is what the TypeScript side calls, and changing
it on one side alone is the drift described above.


WHAT THIS ADDS OVER THE TYPESCRIPT

  * FRONT-ONLY PRODUCTS. `generateClothOnModel` takes a front and a back buffer;
    the regenerate worker quietly passes `imageBuffers[1] || imageBuffers[0]`, so
    a product with one photograph silently hands the model the same picture twice
    and lets it work out that the back is unknown. Here that is explicit: the
    prompt SAYS the rear was never photographed and must be inferred from the
    garment's construction, and the caller is told `back_inferred` so it can be
    surfaced rather than shipped quietly.

  * GAP FILLING. The TypeScript regenerates all five views or one clicked tile.
    Most products missing imagery are missing ONE view, so this generates exactly
    the views asked for and takes the product's existing AI_FRONT render as the
    identity reference — the same `frontReferenceImage` mechanism, pointed at a
    render that already exists. One call instead of five, and the new view matches
    the model already in the gallery.
"""

