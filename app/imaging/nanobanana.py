class NanoBanana:
    """One generation session for one product."""

    def __init__(self, api_keys: str | list[str], pol: dict[str, Any]) -> None:
        from google import genai  # imported lazily so the service boots without it
        from google.genai import types

        self.genai = genai
        # A list, always. Accepting a bare string too keeps the constructor
        # usable from a test or a one-off script without ceremony.
        self.api_keys = [api_keys] if isinstance(api_keys, str) else list(api_keys)
        self._key_index = 0
        self._key_lock = threading.Lock()
        self.cfg = (pol.get("imagery") or {}).get("generation") or {}
        self.model = self.cfg.get("model") or "gemini-3-pro-image-preview"
        self.calls = 0
        self.errors: list[str] = []

        # A render takes minutes, so the SDK's default read timeout is far too
        # short — and on a host that stalls on IPv6, `client_args` is the only way
        # in: the SDK builds its own httpx client, so the transport has to be
        # handed to it rather than configured around it.
        self._timeout_ms = int(float(self.cfg.get("timeout_s") or 300) * 1000)

    def _http_options(self):
        """FRESH HttpOptions — and a fresh transport — for every call.

        Built per call, not once in __init__, and that is the whole point.
        `genai_client_args()` returns an `httpx.HTTPTransport`, which owns a
        connection pool. Cached on the instance, every per-thread `genai.Client`
        got the SAME transport: the four views that run concurrently shared one
        pool, and the moment the first client finished and closed it, the others
        lost their sockets mid-read.

        The symptom was three simultaneous
        `ReadError: [WinError 10038] An operation was attempted on something
        that is not a socket` in the same second one view succeeded — reported
        as three failed views, and indistinguishable in the logs from a model
        refusing the garment.
        """
        from google.genai import types

        return types.HttpOptions(
            timeout=self._timeout_ms,
            client_args=genai_client_args() or None,
        )

    def _next_key(self) -> str:
        """The next generation key, round-robin.

        Locked because views generate on a thread pool: an unguarded
        read-modify-write would hand the same key to two concurrent calls and
        skip another, which is exactly the per-key rate-limit pressure the
        rotation exists to spread.
        """
        with self._key_lock:
            key = self.api_keys[self._key_index % len(self.api_keys)]
            self._key_index += 1
        return key

    # ------------------------------------------------------------------ inputs
    def fetch(self, urls: list[str], timeout: float = 30.0) -> dict[str, bytes]:
        """Download source photographs, concurrently and under a deadline.

        Keyed BY URL, never a positional list. An earlier version returned a list
        with the failures dropped, which quietly renumbered everything after
        them: when a 6 MB front photo truncated mid-download, the caller's
        `buffers[0]` became the BACK photograph and the model was asked to render
        a front view from it. Nothing errored and the output looked plausible.

        Missing keys are the caller's signal that a specific photograph is
        unavailable, which is a decision only it can make — a missing back is
        recoverable, a missing front is not.
        """
        got = fetch_all(urls, timeout_s=timeout, deadline_s=timeout * 2)
        out: dict[str, bytes] = {}
        for url in urls:
            data = got.get(url)
            if data is None:
                msg = f"source fetch failed: {url[:70]}"
                log.warning(msg)
                self.errors.append(msg)
                continue
            out[url] = compress_source(data)
        return out

    # ------------------------------------------------------------------- calls
    def _one(
        self,
        view: str,
        front: bytes,
        back: bytes | None,
        ctx: PromptContext,
        additional: list[bytes],
        front_reference: bytes | None,
        model: str | None = None,
    ) -> tuple[bytes | None, str | None]:
        """One view on one model. Returns (bytes, error) — exactly one is set."""
        from google.genai import types

        model = model or self.model

        prompt = build_prompt(view, ctx, has_front_reference=front_reference is not None)

        parts: list[Any] = [
            types.Part.from_text(text=prompt),
            types.Part.from_bytes(data=front, mime_type="image/jpeg"),
        ]
        if back is not None:
            parts.append(types.Part.from_bytes(data=back, mime_type="image/jpeg"))
        # The reference rides along for every view but the front — which, in a
        # set, IS the reference — unless the identity is being copied from a
        # render the product already has, in which case the front needs it too.
        if front_reference is not None and (view != "front" or ctx.identity_from_reference):
            parts.append(types.Part.from_text(
                text="This is the front view reference - use the EXACT SAME model "
                     "with identical characteristics."
            ))
            parts.append(types.Part.from_bytes(
                data=front_reference, mime_type="image/jpeg"
            ))
        for extra in additional:
            parts.append(types.Part.from_bytes(data=extra, mime_type="image/jpeg"))

        image_config: dict[str, Any] = {
            "image_size": resolve_image_size(
                ctx.settings.resolution, self.cfg.get("default_resolution") or "2K"
            )
        }
        ratio = resolve_aspect_ratio(
            ctx.settings.aspect_ratio, self.cfg.get("supported_aspect_ratios") or []
        )
        if ratio:
            image_config["aspect_ratio"] = ratio

        # A fresh client per call, on the NEXT key, so parallel views spread
        # across the configured keys rather than hammering one — the same
        # `makeClient()`-per-view rotation banana-nano.ts does.
        client = self.genai.Client(
            api_key=self._next_key(),
            http_options=self._http_options(),
        )
        # EXPLICIT SAFETY THRESHOLDS.
        #
        # Left unset, the developer API applies BLOCK_MEDIUM_AND_ABOVE — stricter
        # than Google's own consumer surface, which renders a player-name jersey
        # on a model (back view included) while the identical garment through
        # this API returns IMAGE_OTHER. These are a documented request parameter
        # for exactly this: tuning the threshold to the domain. Second-hand
        # clothing shot for resale is a benign one.
        #
        # A threshold move, not a way around a decision — and it may not help at
        # all, because an image refusal can originate in an output-side filter
        # these do not reach. `safety_relaxed: false` restores the defaults.
        safety = None
        if self.cfg.get("safety_relaxed"):
            try:
                low = types.HarmBlockThreshold.BLOCK_ONLY_HIGH
                safety = [
                    types.SafetySetting(category=c, threshold=low)
                    for c in (
                        types.HarmCategory.HARM_CATEGORY_HARASSMENT,
                        types.HarmCategory.HARM_CATEGORY_HATE_SPEECH,
                        types.HarmCategory.HARM_CATEGORY_SEXUALLY_EXPLICIT,
                        types.HarmCategory.HARM_CATEGORY_DANGEROUS_CONTENT,
                    )
                ]
            except AttributeError as exc:
                # An SDK that names these differently must not take generation
                # down with it — fall back to the API defaults.
                log.warning("safety settings unavailable in this SDK: %s", exc)

        config = types.GenerateContentConfig(
            response_modalities=["IMAGE", "TEXT"],
            image_config=types.ImageConfig(**image_config),
            **({"safety_settings": safety} if safety else {}),
        )
        contents = [types.Content(role="user", parts=parts)]

        # Transient server errors are retried HERE rather than by the caller,
        # for the same reason the TypeScript retries a 429 inside the view rather
        # than in the worker: the worker would re-run the whole job, redoing the
        # views that already succeeded. Observed in practice — a 504
        # DEADLINE_EXCEEDED four seconds into a request that normally takes
        # twenty-five, on a product whose other view was fine.
        #
        # A REFUSAL is never retried here. It is a decision, not a fault, and
        # repeating the identical request gets the identical answer while
        # doubling the latency the operator waits through.
        attempts = int(self.cfg.get("max_retries") or 2) + 1
        backoff = float(self.cfg.get("retry_backoff_s") or 3)
        last = ""
        for attempt in range(attempts):
            self.calls += 1
            try:
                resp = client.models.generate_content(
                    model=model, contents=contents, config=config
                )
                break
            except Exception as exc:  # noqa: BLE001 — one view failing is survivable
                last = f"{type(exc).__name__}: {exc}"
                if attempt + 1 >= attempts or not _is_transient(last):
                    log.warning("nano banana call failed (%s on %s: %s)", view, model, last)
                    return None, last
                log.info("%s failed (%s); retry %d/%d",
                         view, last, attempt + 1, attempts - 1)
                time.sleep(backoff * (attempt + 1))
        else:  # pragma: no cover — the loop always breaks or returns
            return None, last

        for candidate in resp.candidates or []:
            for part in (candidate.content.parts if candidate.content else []) or []:
                inline = getattr(part, "inline_data", None)
                if inline and inline.data:
                    return inline.data, None

        # No image AND no exception — almost always a content decision rather
        # than a fault. Reporting a bare "no image returned" here sent a real
        # investigation down the wrong path for an hour, chasing prompt length
        # and quota when the model was in fact declining a Raptors jersey with a
        # player's name on the back.
        #
        # THREE places carry the reason, and only checking the first left an
        # Aaron Rodgers jersey reported as "no reason given":
        #   * candidate.finish_reason — the usual IMAGE_OTHER / IMAGE_SAFETY
        #   * prompt_feedback.block_reason — set when the REQUEST is blocked
        #     outright, in which case `candidates` is empty and the first check
        #     finds nothing
        #   * a text part — the model sometimes answers in words instead
        parts_of_reason: list[str] = []

        block = getattr(getattr(resp, "prompt_feedback", None), "block_reason", None)
        if block:
            parts_of_reason.append(f"prompt blocked: {block}")

        for candidate in resp.candidates or []:
            finish = getattr(candidate, "finish_reason", None)
            if finish:
                parts_of_reason.append(str(finish))
            for part in (candidate.content.parts if candidate.content else []) or []:
                said = (getattr(part, "text", "") or "").strip()
                if said:
                    parts_of_reason.append(f'model replied: "{said[:160]}"')
            break

        reason = " — ".join(parts_of_reason) or "no image and no reason given"
        log.warning("nano banana produced no image for %s on %s (%s)",
                    view, model, reason)
        return None, reason

    # ----------------------------------------------------------------- the run
    def generate(
        self,
        views: list[str],
        front: bytes,
        back: bytes | None,
        ctx: PromptContext,
        additional: list[bytes] | None = None,
        front_reference: bytes | None = None,
        preferred_model: str | None = None,
    ) -> list[GeneratedView]:
        """Render `views` (VNYX view names) with ONE model, and hand back the bytes.

        ONE MODEL FOR THE WHOLE SET. This used to escalate per view, so a garment
        the primary would render from the front but not from the back came out as
        a Gemini front beside a gpt-image back — two different people in one
        product gallery, which is worse than a missing image because it ships
        looking deliberate.

        The escalation is therefore over the SET: every requested view is tried
        on one model, and only if that model cannot do all of them does the next
        one get a turn. The common case costs exactly what it did before, one
        call per view on the primary; only a product that needs a fallback pays
        for the retries, and it gets a consistent set in exchange.

        `preferred_model` goes to the front of the chain. The caller passes
        whatever produced the renders already on the product, so a gap-fill keeps
        the model that is already in the gallery instead of introducing a second.

        `front_reference` is what keeps one model IDENTITY across a set. When the
        caller supplies one — an AI_FRONT the product already has — every view is
        generated against it. When it does not, the front is generated FIRST and
        becomes the reference for the rest, which is the TypeScript's sequencing
        and the reason the front cannot simply join the parallel batch.
        """
        started = time.perf_counter()
        wanted = [MEDIA_TO_VIEW[v] for v in views if v in MEDIA_TO_VIEW]
        wanted.sort(key=lambda v: VIEW_ORDER.index(v))
        if not wanted:
            return []

        # No back photograph: the front stands in for it, and the prompt says so.
        back_bytes = back if back is not None else front
        extras = (additional or [])[: int(self.cfg.get("max_context_images") or 1)]

        # Every view any model managed, keyed by view. The FIRST model to produce
        # one wins, so a view the primary rendered is never replaced by a later,
        # weaker model's version of it.
        salvage: dict[str, GeneratedView] = {}
        last: list[GeneratedView] = []
        self._attempts: list[list[GeneratedView]] = []

        for model in self._model_chain(preferred_model):
            attempt = self._render_set(
                wanted, front, back_bytes, ctx, extras, front_reference, model
            )
            last = attempt
            self._attempts.append(attempt)
            produced = sum(1 for v in attempt if v.ok)

            if produced == len(wanted):
                if model != self.model:
                    self.errors.append(
                        f"{self.model} could not render every view; the whole set "
                        f"was produced with {model} instead, so they match"
                    )
                self._log_done(attempt, started)
                return attempt

            for view in attempt:
                if view.ok and view.view not in salvage:
                    salvage[view.view] = view
            if produced:
                log.info(
                    "%s rendered %d/%d views; trying the next model for a "
                    "complete set", model, produced, len(wanted),
                )

        # NO single model could do the whole set. Consistency is now unreachable,
        # so the choice is between a complete set from several models and an
        # incomplete one from a single model.
        #
        # Completeness wins, LOUDLY. Discarding a view another model already
        # rendered — which is what keeping one partial did — hands back "could
        # not generate the front" while a perfectly good front sits in memory.
        # A mixed set with a warning is something an operator can look at and
        # judge; a missing image is not.
        if not self.cfg.get("allow_mixed_models", True):
            # Consistency chosen over completeness: hand back the single model's
            # most complete attempt and report the rest as missing.
            best = max(
                self._attempts, key=lambda a: sum(1 for v in a if v.ok), default=[]
            )
            self._log_done(best, started)
            return best

        merged = [salvage[v.view] for v in last if v.view in salvage]
        for view in last:
            if view.view not in salvage:
                merged.append(view)          # keep the failure and its reason
        merged.sort(key=lambda v: VIEW_ORDER.index(MEDIA_TO_VIEW[v.view]))

        models = {v.model for v in merged if v.ok and v.model}
        if len(models) > 1:
            self.errors.append(
                "MIXED MODELS: no single model would render every view, so these "
                f"came from {', '.join(sorted(models))}. They will not look like "
                "the same person — regenerate the set if that matters more than "
                "having the images."
            )

        self._log_done(merged, started)
        return merged

    def _log_done(self, views: list[GeneratedView], started: float) -> None:
        log.info(
            "generated %d/%d views in %.1fs",
            sum(1 for v in views if v.ok), len(views),
            time.perf_counter() - started,
        )

    def _model_chain(self, preferred: str | None) -> list[str]:
        """Every model to try, in order, deduplicated.

        The OpenAI entry is last and only present when it is configured and
        switched on: a different vendor, reached once no Gemini model will take
        the garment.
        """
        chain = [self.model, *(self.cfg.get("fallback_models") or [])]
        if self.cfg.get("openai_fallback") and openai_image.available():
            chain.append(os.getenv("OPENAI_IMAGE_MODEL", "gpt-image-1"))
        if preferred:
            chain.insert(0, preferred)

        seen: set[str] = set()
        return [m for m in chain if m and not (m in seen or seen.add(m))]

    def _render_set(
        self,
        wanted: list[str],
        front: bytes,
        back: bytes,
        ctx: PromptContext,
        extras: list[bytes],
        front_reference: bytes | None,
        model: str,
    ) -> list[GeneratedView]:
        """Every requested view, on ONE model."""
        results: dict[str, tuple[bytes | None, str | None]] = {}
        reference = front_reference
        remaining = list(wanted)

        # The front leads when nothing else establishes the identity, because
        # every other view is generated against it.
        if "front" in remaining and reference is None:
            results["front"] = self._render(
                "front", front, back, ctx, extras, None, model
            )
            reference = results["front"][0]
            remaining.remove("front")

        # The rest depend only on the reference, so they run concurrently — the
        # difference between ~front + 1 view and five in series, which for a
        # button on a product page is minutes.
        if remaining:
            with concurrent.futures.ThreadPoolExecutor(
                max_workers=len(remaining)
            ) as pool:
                futures = {
                    pool.submit(
                        self._render, v, front, back, ctx, [], reference, model
                    ): v
                    for v in remaining
                }
                for future in concurrent.futures.as_completed(futures):
                    results[futures[future]] = future.result()

        # SECOND PASS, same model: a front-facing view that failed may have been
        # blocked by the BACK photograph, which it never needed. Proven on a
        # Raptors jersey whose front reads "TORONTO 10" and whose back reads
        # "DEROZAN 10" — the front renders once the back is out of the request.
        #
        # Retried on the SAME model rather than by escalating, so recovering the
        # view cannot introduce a second model into the set. Never attempted for
        # back views: dropping the back photo there does not route around the
        # refusal, it invents the reverse of a licensed garment.
        retryable = [
            v for v in wanted
            if v not in ("back", "back34")
            and results.get(v, (None, None))[0] is None
            and not _is_transient(results.get(v, (None, None))[1])
        ]
        for view in retryable:
            log.info("%s empty on %s; retrying without the back reference",
                     view, model)
            data, error = self._render(
                view, front, None, ctx, extras if view == "front" else [],
                reference, model,
            )
            if data is not None:
                self.errors.append(
                    f"{VIEW_TO_MEDIA[view]}: {model} produced nothing with both "
                    f"photographs attached; generated from the front alone"
                )
                results[view] = (data, None)
                if view == "front" and reference is None:
                    reference = data

        out: list[GeneratedView] = []
        for view in VIEW_ORDER:
            if view not in results:
                continue
            data, error = results[view]
            if error:
                self.errors.append(f"{VIEW_TO_MEDIA[view]} on {model}: {error}")
            out.append(GeneratedView(
                view=VIEW_TO_MEDIA[view],
                image_base64=base64.b64encode(data).decode() if data else None,
                mime_type="image/jpeg",
                bytes=len(data) if data else 0,
                ok=data is not None,
                error=error,
                model=model if data else None,
            ))
        return out

    def _render(
        self,
        view: str,
        front: bytes,
        back: bytes | None,
        ctx: PromptContext,
        additional: list[bytes],
        front_reference: bytes | None,
        model: str,
    ) -> tuple[bytes | None, str | None]:
        """One view on one model, whichever vendor that model belongs to."""
        if _is_openai_model(model):
            # The front reference is passed HERE too. Omitting it is what let a
            # gpt-image back view invent a different person from the Gemini front
            # standing beside it in the gallery.
            images = [front]
            if back is not None and back is not front:
                images.append(back)
            if front_reference is not None and view != "front":
                images.append(front_reference)
            self.calls += 1
            # THE SHAPE THE PRIMARY WOULD HAVE PRODUCED — which is what this
            # render has to match, since the two sit side by side in one gallery
            # and the product page crops whatever does not fit.
            #
            # Not the tenant's raw setting: Gemini is given
            # `resolve_aspect_ratio(...)`, and a 5:7 tenant has no native Gemini
            # equivalent so it becomes 3:4. Conforming to 5:7 would leave the two
            # vendors a different shape from each other.
            #
            # And not nothing when the tenant says "auto": that is the common
            # case here, and it means Gemini renders unconstrained at its own
            # 27:38 while gpt-image lands on 2:3. `auto_portrait_ratio` is that
            # measured Gemini default.
            resolved_ratio = resolve_aspect_ratio(
                ctx.settings.aspect_ratio,
                self.cfg.get("supported_aspect_ratios") or [],
            ) or self.cfg.get("auto_portrait_ratio")
            return openai_image.generate(
                build_prompt(
                    view, ctx, has_front_reference=front_reference is not None
                ),
                images,
                aspect_ratio=resolved_ratio,
                timeout_s=float(self.cfg.get("timeout_s") or 300),
                quality=self.cfg.get("openai_quality"),
            )

        return self._one(
            view, front, back, ctx, additional, front_reference, model=model
        )


def _is_openai_model(model: str) -> bool:
    return model.lower().startswith(("gpt-image", "dall-e"))


# Finish reasons that mean "the model chose not to", as opposed to a fault.
# Retrying the same request unchanged will not help; the caller needs to know
# the difference so it does not present a policy refusal as a transient error.
_REFUSAL_REASONS = (
    "IMAGE_OTHER", "IMAGE_SAFETY", "IMAGE_PROHIBITED_CONTENT",
    "PROHIBITED_CONTENT", "SAFETY", "RECITATION", "BLOCKLIST",
)


def _is_refusal(error: str | None) -> bool:
    return bool(error) and any(r in error.upper() for r in _REFUSAL_REASONS)


# Faults worth trying again: the provider being briefly unable, not unwilling.
# 504 DEADLINE_EXCEEDED is the one seen most on this model, and it arrives in
# seconds rather than at the end of a long generation.
_TRANSIENT_MARKERS = (
    "429", "500", "502", "503", "504",
    "DEADLINE_EXCEEDED", "UNAVAILABLE", "INTERNAL", "RESOURCE_EXHAUSTED",
    "CONNECTERROR", "READTIMEOUT", "REMOTEPROTOCOLERROR", "TIMEOUT",
    # The httpx transport family. `READTIMEOUT` was here but `READERROR` was
    # not, and they are different exceptions: a socket that DIES mid-read raises
    # ReadError, which matched nothing and was therefore classified as a
    # REFUSAL — so a broken connection was reported as "the model declined this
    # garment", and the caller stopped instead of retrying.
    #
    # Seen as `ReadError: [WinError 10038] An operation was attempted on
    # something that is not a socket`, three views at once.
    "READERROR", "WRITEERROR", "POOLTIMEOUT", "PROXYERROR",
    "LOCALPROTOCOLERROR", "SSLERROR", "CLOSEDRESOURCEERROR",
    # Windows socket errnos, which arrive wrapped rather than named.
    "WINERROR",
)


def _is_transient(error: str | None) -> bool:
    if not error:
        return False
    upper = error.upper()
    # A refusal can carry a 400-ish shape; never let it look retryable.
    if any(r in upper for r in _REFUSAL_REASONS):
        return False
    return any(m in upper for m in _TRANSIENT_MARKERS)
